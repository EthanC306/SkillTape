// Formats whose expected answer is code or ASCII art, so it has to keep its
// own line breaks and column alignment to be readable at all.
const MONO_FORMATS = ["write", "trace", "error", "cloze", "diagram"];

const state = {
  queue: [],
  done: 0,
  busy: false,
};

const root = document.getElementById("root");
const progressEl = document.getElementById("progress");
const errorEl = document.getElementById("error");

function el(tag, className, text) {
  const node = document.createElement(tag);
  if (className) node.className = className;
  if (text !== undefined && text !== null) node.textContent = text;
  return node;
}

function showError(message) {
  errorEl.textContent = message;
  errorEl.classList.remove("hidden");
}

function clearError() {
  errorEl.textContent = "";
  errorEl.classList.add("hidden");
}

function current() {
  return state.queue[0];
}

function renderChoices(item) {
  const list = el("ul", "choices");
  item.choices.forEach((choice, i) => {
    if (i === item.answerIndex) {
      list.appendChild(el("li", "correct", `${choice}   ← correct`));
    } else {
      list.appendChild(el("li", null, choice));
    }
  });
  return list;
}

function renderProvenance(item) {
  const col = el("div", "col");

  if (!item.provenance) {
    col.appendChild(el("div", "label", "Source"));

    let note =
      "No provenance recorded. Authored by hand, so check it against what you know the course actually says.";
    if (item.legacy) {
      note =
        "Legacy question. This shape predates provenance, so there is no excerpt to check against. Verify it on your own knowledge of the course.";
    }
    col.appendChild(el("div", "meta", note));

    if (item.tag) {
      col.appendChild(el("div", "label", "Tag"));
      col.appendChild(el("div", "meta", item.tag));
    }
    if (item.figure) {
      col.appendChild(el("div", "label", "Figure"));
      col.appendChild(el("div", "meta", item.figure));
    }
    return col;
  }

  const p = item.provenance;

  col.appendChild(el("div", "label", "Source excerpt"));
  col.appendChild(el("div", "excerpt", p.excerpt || "(no excerpt)"));

  col.appendChild(el("div", "label", "Citation"));
  const meta = el("div", "meta");
  meta.appendChild(el("div", null, p.citation || "(none)"));
  meta.appendChild(el("div", null, `${p.sourceId || "?"} ${p.anchor || ""}`));
  if (p.page) meta.appendChild(el("div", null, `page ${p.page}`));
  col.appendChild(meta);

  if (item.generationMeta) {
    col.appendChild(el("div", "label", "Generated by"));
    const g = el("div", "meta");
    g.appendChild(el("div", null, item.generationMeta.model || "?"));
    g.appendChild(el("div", null, item.generationMeta.generatedAt || ""));
    g.appendChild(el("div", null, item.generationMeta.promptedFrom || ""));
    col.appendChild(g);
  }

  return col;
}

function renderCard(item) {
  const card = el("div", "card");

  const head = el("div", "card-head");
  head.appendChild(el("span", "badge format", item.format));
  if (item.legacy) {
    head.appendChild(el("span", "badge legacy", "legacy"));
  }
  head.appendChild(el("span", "id", item.id));
  head.appendChild(el("span", "badge", item.topicTitle || item.topicId));
  head.appendChild(el("span", "badge", `difficulty ${item.difficulty}`));
  head.appendChild(el("span", "badge", item.origin));
  if (item.timeBudgetSec) {
    head.appendChild(el("span", "badge", `${item.timeBudgetSec}s`));
  }
  card.appendChild(head);

  const cols = el("div", "cols");
  const left = el("div", "col");

  left.appendChild(el("div", "label", "Prompt"));
  left.appendChild(el("div", "prompt", item.prompt));

  if (item.code) {
    left.appendChild(el("div", "label", "Code"));
    left.appendChild(el("div", "mono", item.code));
  }

  if (Array.isArray(item.choices) && item.choices.length) {
    left.appendChild(el("div", "label", "Choices"));
    left.appendChild(renderChoices(item));
  }

  if (item.expected) {
    left.appendChild(el("div", "label", "Expected answer"));
    let cls = "body";
    if (MONO_FORMATS.includes(item.format)) cls = "mono";
    left.appendChild(el("div", cls, item.expected));
  }

  if (item.explanation) {
    left.appendChild(el("div", "label", "Explanation"));
    left.appendChild(el("div", "body", item.explanation));
  }

  if (Array.isArray(item.criteria) && item.criteria.length) {
    left.appendChild(el("div", "label", "Grading criteria"));
    const list = el("ul", "criteria");
    for (const c of item.criteria) {
      list.appendChild(el("li", null, c));
    }
    left.appendChild(list);
  }

  if (Array.isArray(item.extraAtoms) && item.extraAtoms.length) {
    left.appendChild(el("div", "label", "Extra atoms"));
    const list = el("ul", "criteria");
    for (const a of item.extraAtoms) {
      list.appendChild(el("li", null, a));
    }
    left.appendChild(list);
  }

  left.appendChild(el("div", "label", "File"));
  left.appendChild(el("div", "meta", item.file));

  cols.appendChild(left);
  cols.appendChild(renderProvenance(item));
  card.appendChild(cols);

  const actions = el("div", "actions");
  const no = el("button", "no", "✗  Needs fixing");
  const ok = el("button", "ok", "✓  Verified");
  no.addEventListener("click", reject);
  ok.addEventListener("click", verify);
  actions.appendChild(no);
  actions.appendChild(ok);
  card.appendChild(actions);

  return card;
}

function render() {
  root.replaceChildren();

  const item = current();
  if (!item) {
    progressEl.textContent = `${state.done} reviewed`;
    root.appendChild(el("div", "empty", "Nothing left to review."));
    return;
  }

  progressEl.textContent = `${state.done} reviewed, ${state.queue.length} left`;
  root.appendChild(renderCard(item));
  root.appendChild(el("div", "hint", "J or → to verify, F or ← to flag"));
}

async function post(url, body) {
  const res = await fetch(url, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify(body),
  });
  const data = await res.json();
  if (!res.ok) throw new Error(data.error || res.statusText);
  return data;
}

async function verify() {
  const item = current();
  if (!item || state.busy) return;

  state.busy = true;
  try {
    await post("/api/verify", { id: item.id });
    clearError();
    state.queue.shift();
    state.done++;
    render();
  } catch (err) {
    showError(`Could not verify ${item.id}: ${err.message}`);
  } finally {
    state.busy = false;
  }
}

async function reject() {
  const item = current();
  if (!item || state.busy) return;

  const reason = window.prompt(`What is wrong with ${item.id}?`);
  if (reason === null) return;

  state.busy = true;
  try {
    await post("/api/reject", { id: item.id, reason });
    clearError();
    state.queue.shift();
    state.done++;
    render();
  } catch (err) {
    showError(`Could not flag ${item.id}: ${err.message}`);
  } finally {
    state.busy = false;
  }
}

document.addEventListener("keydown", (e) => {
  const key = e.key.toLowerCase();
  if (key === "j" || e.key === "ArrowRight") {
    verify();
  } else if (key === "f" || e.key === "ArrowLeft") {
    reject();
  }
});

async function load() {
  try {
    const res = await fetch("/api/questions");
    const data = await res.json();
    state.queue = data.questions;
    render();
  } catch (err) {
    showError(`Could not load questions: ${err.message}`);
  }
}

load();
